import { createDeliveryClient, isContentItemOfType } from '@kontent-ai/delivery-sdk';
// TypedClientSchema is generated by the Delivery SDK model generator
// Tip: Generate it with https://www.npmjs.com/package/@kontent-ai/delivery-sdk-model-generator
import { TypedClientSchema } from './models';
import { Author } from './models/Author';
import { SimpleArticle } from './models/SimpleArticle';

const deliveryClient = createDeliveryClient<TypedClientSchema, SimpleArticle | Author>({
  apiMode: 'public',
  environmentId: '8d20758c-d74c-4f59-ae04-ee928c0816b7'
});

const response = await deliveryClient.fetchContentItem({
  codename: 'the_origin_of_coffee',
  query: { depth: 1 }
})
  .fetch();

const article = response.payload.item;

// Narrows the item to the SimpleArticle model based on its content type
if (isContentItemOfType(article, 'article')) {
  // Gets the resolved author from the linked items element
  const author: Author | undefined = article.elements.author.items[0];
}
