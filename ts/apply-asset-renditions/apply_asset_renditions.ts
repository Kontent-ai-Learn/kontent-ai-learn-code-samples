// @kontent-ai/delivery-sdk v16
import { createDeliveryClient } from '@kontent-ai/delivery-sdk';

// Specifies which asset rendition to use by default by providing defaultRenditionPreset
const deliveryClient = createDeliveryClient({
  environmentId: 'KONTENT_AI_ENVIRONMENT_ID',
  // Automatically applies the 'default' asset rendition if assets specify it
  defaultRenditionPreset: 'default'
});

// Requests a content item
const response = await deliveryClient.item('my_article')
  .toPromise();

// Gets the first asset in the 'teaser_image' asset element
const asset = response.data.item.elements.teaser_image.value[0];

// Gets the asset's URL. If the asset specifies a rendition, it's automatically applied.
const assetUrl = asset.url;

// @kontent-ai/delivery-sdk v17
import { createDeliveryClient, isContentItemOfType } from '@kontent-ai/delivery-sdk';
// TypedClientSchema and TypedItem are generated by the Delivery SDK model generator
// Tip: Generate them with https://www.npmjs.com/package/@kontent-ai/delivery-sdk-model-generator
import { TypedClientSchema, TypedItem } from './models';

const deliveryClient = createDeliveryClient<TypedClientSchema, TypedItem>({
  apiMode: 'public',
  environmentId: 'KONTENT_AI_ENVIRONMENT_ID'
});

// Requests a content item
const response = await deliveryClient.fetchContentItem({ codename: 'my_article' })
  .fetch();

const item = response.payload.item;

if (isContentItemOfType(item, 'article')) {
  // Gets the first asset in the 'teaser_image' asset element
  const asset = item.elements.teaser_image.value[0];

  // Gets the 'default' asset rendition if the asset specifies it
  const rendition = asset.renditions.default;

  // Gets the asset's URL. Renditions aren't applied automatically, so the rendition query is appended to the URL.
  const assetUrl = rendition ? `${asset.url}?${rendition.query}` : asset.url;
}
