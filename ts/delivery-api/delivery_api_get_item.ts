// @kontent-ai/delivery-sdk v16
import { createDeliveryClient, IContentItem, Elements } from '@kontent-ai/delivery-sdk';

const deliveryClient = createDeliveryClient({
  environmentId: 'KONTENT_AI_ENVIRONMENT_ID'
});

export type Article = IContentItem<{
  title: Elements.TextElement;
  summary: Elements.RichTextElement;
  post_date: Elements.DateTimeElement;
  teaser_image: Elements.AssetsElement;
  related_articles: Article[];
}>;

// Tip: Create strongly typed models according to https://kontent.ai/learn/strongly-typed-models
const response = await deliveryClient.item<Article>('my_article')
  .toPromise();

// @kontent-ai/delivery-sdk v17
import { createDeliveryClient, ContentItemOf, Elements } from '@kontent-ai/delivery-sdk';
// TypedClientSchema is generated by the Delivery SDK model generator
// Tip: Generate it with https://www.npmjs.com/package/@kontent-ai/delivery-sdk-model-generator
import { TypedClientSchema } from './models';

export type Article = ContentItemOf<TypedClientSchema, 'article', {
  title: Elements.Text;
  summary: Elements.RichText;
  post_date: Elements.DateTime;
  teaser_image: Elements.Asset;
  related_articles: Elements.LinkedItems<Article>;
}>;

// Tip: Create strongly typed models according to https://kontent.ai/learn/strongly-typed-models
const deliveryClient = createDeliveryClient<TypedClientSchema, Article>({
  apiMode: 'public',
  environmentId: 'KONTENT_AI_ENVIRONMENT_ID'
});

const response = await deliveryClient.fetchContentItem({ codename: 'my_article' })
  .fetch();
