import { ContentItemOf, createDeliveryClient, Elements } from '@kontent-ai/delivery-sdk';
// TypedClientSchema is generated by the Delivery SDK model generator
// Tip: Generate it with https://www.npmjs.com/package/@kontent-ai/delivery-sdk-model-generator
import { TypedClientSchema } from './models';

// Tip: Create strongly typed models according to https://kontent.ai/learn/strongly-typed-models
export type Article = ContentItemOf<TypedClientSchema, 'article', {
	 title: Elements.Text;
	 summary: Elements.Text;
	 post_date: Elements.DateTime;
	 teaser_image: Elements.Asset;
	 related_articles: Elements.LinkedItems<Article>;
}>;

const deliveryClient = createDeliveryClient<TypedClientSchema, Article>({
	apiMode: 'secure', // Queries the Delivery API using secure access.
	environmentId: 'KONTENT_AI_ENVIRONMENT_ID',
	deliveryApiKey: 'KONTENT_AI_DELIVERY_API_KEY',
});

const response = await deliveryClient
	.fetchContentItem({ codename: 'my_article' })
	.fetch();
